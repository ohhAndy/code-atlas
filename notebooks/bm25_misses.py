"""Failure-analysis material for BM25 on dev: every dev instance where no gold chunk is in
the top 10 (function-level Hit@10 = 0), written to notebooks/bm25_misses_dev.md.

Per miss: the issue text, the gold patch, each gold chunk's rank in the top 1000 with the
query tokens that score it, and the top 3 retrieved chunks with the tokens that put them
there. A token's contribution is its BM25 term for that chunk, idf * tf part; a chunk's
score is the sum of its contributions.

Run: uv run python notebooks/bm25_misses.py results/bm25_dev_<time>.json
"""

import json
import sys
from pathlib import Path

from code_atlas.eval.dataset import load_instances
from code_atlas.eval.repos import snapshot
from code_atlas.lexical.bm25 import idf
from code_atlas.lexical.cache import INDEX_CACHE_DIR
from code_atlas.lexical.retriever import BM25Retriever
from code_atlas.lexical.tokenizer import tokenize
from code_atlas.parse.chunks import chunk_file

DEEP_K = 1000
TOP_SHOWN = 3
TOKENS_SHOWN = 8
PREVIEW_LINES = 12
OUT = Path(__file__).parent / "bm25_misses_dev.md"


def contributions(r: BM25Retriever, query_tokens: list[str], chunk_id: str) -> list[tuple]:
    """(token, tf, idf, contribution) for each distinct query token in the chunk, largest
    contribution first."""
    index = r.index
    dl = index.doc_lengths[chunk_id]
    norm = 1 - r.b + r.b * dl / index.avg_doc_length
    rows = []
    for token in dict.fromkeys(query_tokens):
        postings = index.postings.get(token)
        if not postings:
            continue
        tf = dict(postings).get(chunk_id)
        if tf is None:
            continue
        w = idf(len(postings), index.num_docs)
        rows.append((token, tf, w, w * tf * (r.k1 + 1) / (tf + r.k1 * norm)))
    return sorted(rows, key=lambda row: -row[3])


def token_table(rows: list[tuple]) -> list[str]:
    if not rows:
        return ["", "  (no query token occurs in this chunk)", ""]
    out = ["", "  | token | tf | idf | contribution |", "  |---|---|---|---|"]
    for token, tf, w, c in rows[:TOKENS_SHOWN]:
        out.append(f"  | `{token}` | {tf} | {w:.2f} | {c:.2f} |")
    if len(rows) > TOKENS_SHOWN:
        rest = sum(row[3] for row in rows[TOKENS_SHOWN:])
        out.append(f"  | ({len(rows) - TOKENS_SHOWN} more) | | | {rest:.2f} |")
    return [*out, ""]


def chunk_preview(repo_dir: Path, chunk_id: str) -> list[str]:
    path = chunk_id.split("::", 1)[0]
    for chunk in chunk_file(path, (repo_dir / path).read_bytes()):
        if chunk.id == chunk_id:
            lines = chunk.text.splitlines()
            shown = lines[:PREVIEW_LINES]
            more = [f"# ... {len(lines) - PREVIEW_LINES} more lines"] if len(lines) > PREVIEW_LINES else []
            return ["  ```python", *(f"  {line}" for line in shown + more), "  ```"]
    return ["  (chunk not found)"]


def main() -> None:
    results_path = Path(sys.argv[1])
    results = json.loads(results_path.read_text())
    assert results["meta"]["method"] == "bm25" and results["meta"]["split"] == "dev"
    by_id = {i.instance_id: i for i in load_instances()}
    misses = [
        r for r in results["instances"]
        if r["function_scores"] is not None and r["function_scores"]["hit@10"] == 0
    ]

    md = [
        "# BM25 dev misses",
        "",
        f"Generated by `notebooks/bm25_misses.py` from `{results_path}` "
        f"(commit `{results['meta']['codeatlas']['commit'][:7]}`). Do not edit by hand.",
        "",
        f"{len(misses)} of {len(results['instances'])} dev instances have no gold chunk in "
        "the top 10. Each section ends with an empty **Why it failed** line to fill in "
        "the project log.",
        "",
    ]
    for res in misses:
        inst = by_id[res["instance_id"]]
        repo_dir = snapshot(inst.repo, inst.base_commit)
        r = BM25Retriever(repo_dir, cache_dir=INDEX_CACHE_DIR)
        q = tokenize(inst.problem_statement)
        distinct = list(dict.fromkeys(q))
        in_vocab = [t for t in distinct if t in r.index.postings]
        deep = r.search(inst.problem_statement, DEEP_K)
        rank = {h.id: n for n, h in enumerate(deep, 1)}
        score = {h.id: h.score for h in deep}
        file_rank = next(
            (n for n, f in enumerate(res["ranking"], 1) if f in res["gold_files"]), None
        )

        md += [
            "---",
            "",
            f"## {inst.instance_id}",
            "",
            f"- Repo: {inst.repo}; category: {res['category']}",
            f"- Query: {len(q)} tokens, {len(distinct)} distinct, {len(in_vocab)} in the "
            f"index vocabulary; {r.index.num_docs} chunks in the snapshot, average length "
            f"{r.index.avg_doc_length:.0f} tokens",
            f"- Gold file rank (file level, top 10): {file_rank or 'not in top 10'}",
            "",
            "### Issue text",
            "",
            "```text",
            inst.problem_statement.strip(),
            "```",
            "",
            "### Gold patch",
            "",
            "```diff",
            inst.patch.strip(),
            "```",
            "",
            "### Gold chunks",
            "",
        ]
        for gold_id in res["gold_chunks"]:
            where = (
                f"rank {rank[gold_id]}, score {score[gold_id]:.2f}"
                if gold_id in rank
                else f"not in top {DEEP_K}"
            )
            md += [
                f"- `{gold_id}`: {where}; length {r.index.doc_lengths[gold_id]} tokens",
                *token_table(contributions(r, q, gold_id)),
                *chunk_preview(repo_dir, gold_id),
                "",
            ]
        md += [f"### Top {TOP_SHOWN} retrieved", ""]
        for n, hit in enumerate(deep[:TOP_SHOWN], 1):
            md += [
                f"{n}. `{hit.id}`: score {hit.score:.2f}; length "
                f"{r.index.doc_lengths[hit.id]} tokens",
                *token_table(contributions(r, q, hit.id)),
                "",
            ]
        md += ["### Why it failed", "", "_(your analysis)_", ""]
        print(f"{inst.instance_id}: done")

    OUT.write_text("\n".join(md) + "\n")
    print(f"Wrote {OUT} ({len(misses)} misses)")


if __name__ == "__main__":
    main()
